CREATE TABLE IF NOT EXISTS public.child_photos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id bigint NOT NULL REFERENCES public.registrations(id) ON DELETE CASCADE,
  storage_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (registration_id, storage_key)
);

DO $$
DECLARE
  legacy RECORD;
  child_key bigint;
  guardian_key bigint;
  rank_key bigint;
  club_key bigint;
  birth_date date;
  guardian_first text;
  guardian_last text;
  photo_key text;
BEGIN
  FOR legacy IN SELECT * FROM public.registrations WHERE child_id IS NULL LOOP
    IF legacy.child_dob !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' OR
       substring(legacy.child_dob, 1, 4)::integer < 1900 THEN
      CONTINUE;
    END IF;
    BEGIN
      birth_date := legacy.child_dob::date;
    EXCEPTION
      WHEN datetime_field_overflow OR invalid_datetime_format THEN
        CONTINUE;
    END;

    guardian_first := COALESCE(NULLIF(split_part(trim(legacy.guardian_name), ' ', 1), ''), 'Guardian');
    guardian_last := COALESCE(NULLIF(trim(substring(trim(legacy.guardian_name)
      FROM length(split_part(trim(legacy.guardian_name), ' ', 1)) + 1)), ''), 'Not provided');

    INSERT INTO public.children (full_name, date_of_birth, gender)
      VALUES (legacy.child_name, birth_date, 'prefer_not_to_say') RETURNING id INTO child_key;
    INSERT INTO public.guardians (first_name, last_name, relationship, phone, email, town_region)
      VALUES (guardian_first, guardian_last, legacy.guardian_relationship, legacy.guardian_phone,
        COALESCE(legacy.guardian_email, ''), legacy.location) RETURNING id INTO guardian_key;
    SELECT id INTO rank_key FROM public.ranks WHERE name = legacy.rank LIMIT 1;
    SELECT id INTO club_key FROM public.clubs WHERE name = upper(legacy.club_name) LIMIT 1;

    UPDATE public.registrations SET child_id = child_key, guardian_id = guardian_key,
      rank_id = rank_key, club_id = club_key, gender = 'prefer_not_to_say'
      WHERE id = legacy.id;

    IF legacy.identification_type IN ('Ghana Card', 'Birth certificate', 'Health insurance', 'Passport') THEN
      INSERT INTO public.child_documents
        (registration_id, document_type, document_number, storage_key)
        VALUES (legacy.id, legacy.identification_type, COALESCE(legacy.identification_number, ''),
          COALESCE(legacy.identification_file, ''));
    END IF;

    FOR photo_key IN SELECT jsonb_array_elements_text(COALESCE(legacy.photos, '[]')::jsonb) LOOP
      IF photo_key ~ '^[0-9a-f-]{36}\.(jpg|png|gif|webp)$' THEN
        INSERT INTO public.child_photos (registration_id, storage_key)
          VALUES (legacy.id, photo_key) ON CONFLICT DO NOTHING;
      END IF;
    END LOOP;
  END LOOP;
END $$;

