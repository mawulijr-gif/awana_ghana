CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text UNIQUE NOT NULL,
  password text NOT NULL,
  role text NOT NULL DEFAULT 'administrator'
);

CREATE TABLE IF NOT EXISTS public.enquiries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text,
  email text,
  telephone text,
  organisation text,
  subject text,
  message text,
  status text DEFAULT 'New',
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.registrations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_name text NOT NULL,
  child_dob text NOT NULL,
  programme text NOT NULL,
  guardian_name text NOT NULL,
  guardian_relationship text NOT NULL,
  guardian_phone text NOT NULL,
  guardian_email text NOT NULL DEFAULT '',
  location text NOT NULL,
  consent smallint NOT NULL DEFAULT 0,
  rank text NOT NULL DEFAULT '',
  club_name text NOT NULL DEFAULT '',
  photos text NOT NULL DEFAULT '[]',
  identification_type text NOT NULL DEFAULT '',
  identification_file text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.subscribers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name text,
  last_name text,
  email text UNIQUE,
  location text,
  consent smallint DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text,
  summary text,
  date text,
  time text,
  venue text,
  status text DEFAULT 'Published'
);

CREATE TABLE IF NOT EXISTS public.faqs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text,
  question text,
  answer text,
  sort_order integer DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.cms_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL,
  slug text NOT NULL,
  title text NOT NULL,
  summary text NOT NULL DEFAULT '',
  body text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  event_date text NOT NULL DEFAULT '',
  event_time text NOT NULL DEFAULT '',
  venue text NOT NULL DEFAULT '',
  link_url text NOT NULL DEFAULT '',
  published smallint NOT NULL DEFAULT 1,
  sort_order integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (type, slug)
);

CREATE TABLE IF NOT EXISTS public.site_settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

